import { describe, expect, it } from 'vitest'
import { parseBrief } from '@/lib/brief'
import { foldSection, type ChecklistItem } from '@/lib/checklist-fold'

/**
 * Счёт «в брифе: N» — сколько ШТУК уже записано. Вынесено из
 * `checklist-fold.test.ts` отдельным файлом: здесь самые дорогие случаи
 * этого шаблона — многоколоночные таблицы городов и услуг и трёхъязычные
 * тексты страниц, — и держать их вместе со свёрткой значило бы вырастить
 * один файл за 150 строк.
 */
const one = (text: string): ChecklistItem => foldSection(parseBrief(text)[0]).items[0]

/**
 * «В брифе: N» считает ШТУКИ, а не единицы парсера. Штука — пункт списка
 * или строка таблицы целиком; заполнена, когда заполнены все её единицы.
 * Разница видна там, где на пункт приходится несколько единиц: FAQ
 * (вопрос + ответ) и тексты страниц услуг (слаг + два языка).
 */
describe('foldSection: «в брифе» считает штуки, а не единицы парсера', () => {
  const faq = (items: string) => one(`## 1. Раздел\n**Частые вопросы:**\n${items}\n`)

  it('восемь вопросов с ответами дают восемь, а не шестнадцать', () => {
    const items = Array.from(
      { length: 8 },
      (_, index) => `${index + 1}. **Вопрос:** Вопрос ${index + 1}?\n   **Ответ:** Ответ ${index + 1}.`,
    ).join('\n')
    expect(faq(items).inBrief).toBe(8)
  })

  it('вопрос без ответа — ещё не штука: подпись обещает «с ответами»', () => {
    const item = faq('1. **Вопрос:** Сколько стоит?\n   **Ответ:**\n2. **Вопрос:**\n   **Ответ:**')
    expect(item.done).toBe(false)
    expect(item.inBrief).toBe(0)
  })

  // Двуязычный шаблон: текст страницы услуги — три единицы (слаг и два
  // языка), и пока казахского нет, страница услуги наполовину пуста.
  it('текст услуги без казахской половины — ещё не штука', () => {
    const texts = (kk: string) =>
      one(
        '## 4. Контент\n**Тексты страниц услуг:**\n' +
          '1. **Слаг:** santehnik\n   **Текст (русский):** Течь, засор.\n   **Текст (қазақша):**' +
          kk +
          '\n',
      )
    expect(texts('').inBrief).toBe(0)
    expect(texts(' Ағып кету, бітелу.').inBrief).toBe(1)
  })

  /**
   * Строка таблицы — ОДНА единица парсера: он считает её заполненной,
   * если непуста хоть одна ячейка. Из этого прямо следует ответ на вопрос
   * про необязательную цену услуги: пустая цена не делает строку неполной,
   * и «в брифе» не разойдётся с `pnpm check-brief` — они считают одно и то же.
   */
  it('строка таблицы услуг с пустой ценой — полноценная штука', () => {
    const prices = '## 4. Контент\n**Услуги — общие данные:**\n\n| Слаг | Цена от (₸) |\n| --- | --- |\n'
    expect(one(prices + '| santehnik |  |\n| elektrik | 15000 |\n').inBrief).toBe(2)
    expect(one(prices + '|  |  |\n| elektrik | 15000 |\n').inBrief).toBe(1)
  })

  it('у пунктов из одной единицы счёт прежний', () => {
    const list = (items: string) => one(`## 1. Раздел\n**Отзывы клиентов:**\n${items}\n`)
    expect(list('1. Айгуль\n2. Ерлан\n3. Дана').inBrief).toBe(3)
    expect(list('1. Айгуль\n2.\n3.').inBrief).toBe(1)
  })
})
