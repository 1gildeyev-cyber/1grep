import { describe, expect, it } from 'vitest'
import { parseBrief } from '@/lib/brief'
import { foldSection, type ChecklistItem } from '@/lib/checklist-fold'

/**
 * Арифметика чек-листа: раздел брифа → пункты «что собрать». Деление
 * на Блок А и Блок Б — в соседнем `checklist.test.ts`, хранение галочек —
 * в `checklist-ticks.test.ts`.
 *
 * Разделы собираются настоящим `parseBrief`, а не выдуманным
 * `BriefSection`: свёртка живёт ровно на тех именах, которые парсер даёт
 * таблицам и спискам, и подделка этих имён проверяла бы не то.
 */
const fold = (text: string): ChecklistItem[] => foldSection(parseBrief(text)[0]).items
const one = (text: string): ChecklistItem => fold(text)[0]
const labels = (text: string): string[] => fold(text).map((item) => item.label)

describe('foldSection: повторы сворачиваются в один пункт', () => {
  it('три пустые строки списка дают один пункт с именем метки', () => {
    expect(labels('## 1. Раздел\n**Отзывы клиентов:**\n1.\n2.\n3.\n')).toEqual(['Отзывы клиентов'])
  })

  it('вопрос и ответ FAQ — одна вещь, которую надо собрать', () => {
    const faq = '## 1. Раздел\n**Частые вопросы:**\n1. **Вопрос:**\n   **Ответ:**\n2. **Вопрос:**\n   **Ответ:**\n'
    expect(labels(faq)).toEqual(['Частые вопросы'])
  })

  it('строки таблицы сворачиваются так же', () => {
    const table = '## 1. Раздел\n**Услуги:**\n\n| А | Б |\n| --- | --- |\n|  |  |\n|  |  |\n'
    expect(labels(table)).toEqual(['Услуги'])
  })

  // Города в этом шаблоне разложены по трём таблицам: общие данные и по
  // таблице падежей на каждый язык. Это три разные вещи, которые автор
  // сайта приносит по отдельности, поэтому и пунктов должно быть три —
  // сворачивается каждая таблица сама в себя, а не все три в одну.
  it('три таблицы городов дают три пункта, а не один', () => {
    const cities =
      '## 2. Языки и география\n' +
      '**Города — общие данные:**\n\n| Слаг | Широта |\n| --- | --- |\n|  |  |\n\n' +
      '**Города — падежи, русский:**\n\n| Слаг | Название |\n| --- | --- |\n|  |  |\n\n' +
      '**Города — падежи, қазақша:**\n\n| Слаг | Название |\n| --- | --- |\n|  |  |\n'
    expect(labels(cities)).toEqual([
      'Города — общие данные',
      'Города — падежи, русский',
      'Города — падежи, қазақша',
    ])
  })
})

/**
 * Сам отмечается ТОЛЬКО одиночный пункт — тот, что вырос из одного поля
 * `- **Поле:**`. У свёрнутого «заполнено» вывести нельзя: шаблон не знает,
 * сколько у бизнеса городов, услуг и отзывов. Поэтому у него живая галочка,
 * а рядом `inBrief` — сколько штук уже записано.
 */
describe('foldSection: отмечается само только одиночное поле', () => {
  it('одиночное поле с текстом — отмечено и заблокировано', () => {
    const section = '## 1. Раздел\n- **Телефон:**\n- **Email:** a@b.kz\n'
    expect(fold(section)).toEqual([
      { id: 'Раздел::Телефон', label: 'Телефон', done: false, inBrief: 0 },
      { id: 'Раздел::Email', label: 'Email', done: true, inBrief: 0 },
    ])
  })

  it('свёрнутый пункт не отмечается сам даже при всех заполненных строках', () => {
    const item = one('## 1. Раздел\n**Отзывы клиентов:**\n1. Всё понравилось, Айгуль\n2. Спасибо, Ерлан\n')
    expect(item.done).toBe(false)
    expect(item.inBrief).toBe(2)
  })

  it('пустой свёрнутый пункт показывает ноль', () => {
    expect(one('## 1. Раздел\n**Отзывы клиентов:**\n1.\n2.\n3.\n')).toEqual({
      id: 'Раздел::Отзывы клиентов',
      label: 'Отзывы клиентов',
      done: false,
      inBrief: 0,
    })
  })

  /**
   * Метка, встретившаяся хоть раз с номером, свёрнута навсегда. Так
   * выглядит недоделанная правка: под одной подводкой две таблицы, в первой
   * строки есть, у второй остался только заголовок. Пустая таблица даёт
   * единицу БЕЗ номера (`closeTable` в `lib/brief.ts`), и если бы она
   * возвращала метку в одиночные, пункт погасил бы себя сам — «уже
   * собрано» при одной строке из двух таблиц.
   */
  it('пустая таблица под той же подводкой не возвращает пункт в одиночные', () => {
    const two =
      '## 2. Языки и география\n**Города — общие данные:**\n\n' +
      '| Слаг | Широта |\n| --- | --- |\n| almaty | 43.2 |\n\n' +
      '| Слаг | Широта |\n| --- | --- |\n'
    expect(one(two)).toMatchObject({ done: false, inBrief: 1 })
  })

  it('таблица из одной строки — тоже свёрнутый пункт, а не одиночное поле', () => {
    const table = '## 1. Раздел\n**Услуги:**\n\n| А | Б |\n| --- | --- |\n| Уборка | раз в неделю |\n'
    expect(one(table)).toMatchObject({ done: false, inBrief: 1 })
  })
})

/**
 * Порядок пунктов = порядок брифа. Раньше `foldSection` перебирал сначала
 * `section.filled`, потом `section.empty`, и наверх группы всплывало всё,
 * где заполнена хоть ОДНА единица парсера, — включая пункты, у которых
 * «в брифе» показывает ноль (вопрос FAQ без ответа). Верх группы читался
 * как «вот это уже собрано», а список переставлялся после каждого захода
 * `/start`.
 */
describe('foldSection: порядок пунктов — порядок брифа', () => {
  it('заполненное поле не всплывает выше пустых, стоящих раньше него', () => {
    const section = '## 1. Раздел\n- **Первое:**\n- **Второе:** есть\n- **Третье:**\n'
    expect(labels(section)).toEqual(['Первое', 'Второе', 'Третье'])
  })

  it('пункт с начатой, но не полной штукой остаётся на своём месте', () => {
    // «Частые вопросы» — вопрос без ответа: заполнена одна единица из двух,
    // «в брифе» покажет ноль. Наверх группы этот пункт попасть не должен.
    const section =
      '## 4. Контент\n' +
      '**Отзывы клиентов:**\n1.\n2.\n\n' +
      '**Частые вопросы:**\n1. **Вопрос:** Сколько стоит?\n   **Ответ:**\n\n' +
      '**Преимущества:**\n1.\n'
    expect(labels(section)).toEqual(['Отзывы клиентов', 'Частые вопросы', 'Преимущества'])
    expect(fold(section)[1]).toMatchObject({ done: false, inBrief: 0 })
  })
})

describe('foldSection: подписи для человека', () => {
  it('снимает номер раздела и обратные кавычки разметки', () => {
    const group = foldSection(parseBrief('## 2. Языки и география\n- **Языки сайта (`ru` / `ru,kk`):**\n')[0])
    expect(group.name).toBe('Языки и география')
    expect(group.items[0].label).toBe('Языки сайта (ru / ru,kk)')
  })
})
