import { describe, expect, it } from 'vitest'
import { parseBrief } from '@/lib/brief'

/**
 * Документ целиком: как единицы разметки (их разбор — соседний
 * `brief.test.ts`) складываются в разделы и в счётчик заполненности,
 * который видит автор сайта в `pnpm check-brief` и в чек-листе главной.
 */
const one = (text: string) => parseBrief(text)[0]

describe('parseBrief: раздел закрыт только целиком', () => {
  it('заполненное поле не закрывает раздел с пустой таблицей и списком', () => {
    const section = one(
      '## Раздел\n- **Телефон:** +7 700 000 00 00\n\n**Услуги:**\n\n| А | Б |\n| --- | --- |\n|  |  |\n\n**Преимущества:**\n1.\n',
    )
    expect(section.filled).toEqual(['Телефон'])
    expect(section.empty).toEqual(['Услуги №1', 'Преимущества №1'])
  })
})

/**
 * Раньше здесь читался настоящий `brief.md` и проверялось, что все его
 * поля лежат в `empty`. Это утверждение не про парсер, а про содержимое
 * шаблона — и краснело оно ровно тогда, когда ученик делал первый
 * документированный шаг: заполнял бриф и звал `/brand-init`.
 *
 * Разделение ролей: утверждать содержимое шаблона — работа guard-теста
 * (`tests/placeholders.test.ts`), он для того и вынесен из `pnpm test:unit`
 * отдельным прогоном. Все остальные тесты проверяют поведение кода
 * на своих данных и обязаны переживать заполненный проект.
 *
 * Формы документа ниже — те же, что в настоящем брифе: многоколоночная
 * таблица городов, две языковые таблицы падежей, таблица услуг
 * и нумерованный список «Тексты страниц услуг» с вложенными полями.
 * Один и тот же документ собирается пустым и заполненным, поэтому
 * проверяется не только разбор, но и то, что заполнение НЕ меняет
 * структуру — а только перекладывает пункты из `empty` в `filled`.
 */
function briefLike(filled: boolean): string {
  const cells = (...values: string[]) => `| ${values.map((value) => (filled ? value : ' ')).join(' | ')} |`
  const value = (text: string) => (filled ? ` ${text}` : '')

  return `## 2. Языки и география

- **Город(а) работы:**${value('Алматы')}

**Города — общие данные** (слаг — латиницей, через дефис):

| Слаг | Широта | Долгота | Телефон филиала |
| --- | --- | --- | --- |
${cells('almaty', '43.238949', '76.889709', '+7 727 350 12 12')}

**Города — падежи, русский** (тот же слаг):

| Слаг | Название | «в ком/чём» | «по кому/чему» |
| --- | --- | --- | --- |
${cells('almaty', 'Алматы', 'в Алматы', 'по Алматы')}

**Города — падежи, қазақша** (тот же слаг):

| Слаг | Название | «в ком/чём» | «по кому/чему» |
| --- | --- | --- | --- |
${cells('almaty', 'Алматы', 'Алматыда', 'Алматы бойынша')}

## 4. Контент

**Услуги — русский** (тот же слаг):

| Слаг | Название | Краткое описание (для карточки) |
| --- | --- | --- |
${cells('santehnik', 'Вызов сантехника', 'Течь, засор, замена смесителя.')}

**Тексты страниц услуг** (по одному пункту на услугу):

1. **Слаг:**${value('santehnik')}
   **Текст (русский):**${value('Развёрнутый текст страницы услуги.')}
   **Текст (қазақша):**${value('Қызмет бетінің толық мәтіні.')}
`
}

/** Имена, которые парсер обязан выдать для документа такой формы. */
const GEO_UNITS = [
  'Город(а) работы',
  'Города — общие данные №1',
  'Города — падежи, русский №1',
  'Города — падежи, қазақша №1',
]
const CONTENT_UNITS = [
  'Услуги — русский №1',
  'Тексты страниц услуг №1: Слаг',
  'Тексты страниц услуг №1: Текст (русский)',
  'Тексты страниц услуг №1: Текст (қазақша)',
]

describe('parseBrief: документ формы настоящего брифа', () => {
  const sectionsOf = (filled: boolean) => parseBrief(briefLike(filled))
  const find = (filled: boolean, name: string) => sectionsOf(filled).find((section) => section.name === name)!

  it('в пустом документе видит города: общие данные и обе таблицы падежей', () => {
    expect(find(false, '2. Языки и география').empty).toEqual(GEO_UNITS)
    expect(find(false, '2. Языки и география').filled).toEqual([])
  })

  it('в пустом документе видит услуги и вложенные поля текстов страниц', () => {
    expect(find(false, '4. Контент').empty).toEqual(CONTENT_UNITS)
    expect(find(false, '4. Контент').filled).toEqual([])
  })

  it('тот же документ с данными даёт те же имена, но заполненными', () => {
    expect(find(true, '2. Языки и география').filled).toEqual(GEO_UNITS)
    expect(find(true, '2. Языки и география').empty).toEqual([])
    expect(find(true, '4. Контент').filled).toEqual(CONTENT_UNITS)
    expect(find(true, '4. Контент').empty).toEqual([])
  })

  // Инвариант, ради которого этот блок и переписан: заполнение брифа
  // не имеет права ни добавить единицу подсчёта, ни потерять её —
  // счётчик «87/87» обязан считать ровно то же, что «0/87».
  it('набор единиц подсчёта не зависит от того, заполнен документ или нет', () => {
    const names = (filled: boolean) =>
      sectionsOf(filled)
        .flatMap((section) => [...section.filled, ...section.empty])
        .sort()

    expect(names(true)).toEqual(names(false))
  })

  it('раздел «Контент» не сводится к одному полю', () => {
    const content = find(false, '4. Контент')
    expect(content.filled.length + content.empty.length).toBeGreaterThan(1)
  })
})

