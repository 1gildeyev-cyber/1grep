'use client'

import { useState } from 'react'
// usePathname берётся из i18n/navigation, а не из next/navigation: первый
// возвращает путь БЕЗ языкового префикса, второй — с ним. Возьми не тот —
// parsePath ниже разберёт язык как часть логического пути, и переключатель
// молча начнёт уводить не туда.
import { useRouter, usePathname } from '@/i18n/navigation'
import { parsePath } from '@/lib/geo/parse-path'
import { cityPath } from '@/lib/geo/city-path'

export const ALL_CITIES = '__all__'

/**
 * Общая логика смены города. Разбирает текущий путь на язык, город
 * и логический хвост (parsePath) и подменяет ровно один сегмент, поэтому
 * со страницы услуги человек остаётся на этой же услуге в другом городе,
 * а не улетает на главную города.
 *
 * **Выбор города никуда не сохраняется — и это решение, а не упущение.**
 * Раньше здесь была кука `city` и роут `/api/city`, который её писал.
 * Прочитать её мог только клиент (чтение на сервере значит `cookies()`
 * в дереве страницы, то есть весь маршрут из статики в динамику — размен,
 * от которого отказались ещё в `app/not-found.tsx`), а клиент читает её
 * после гидратации. Замер на собранном шаблоне: переключатель показывал
 * «Весь Казахстан» 118 мс на десктопе и 478 мс при десятикратном
 * замедлении процессора — то есть у посетителя с дешёвым телефоном
 * почти полсекунды стоял чужой ответ, а потом сам менялся на его.
 * Мигание видно ровно тому, ради кого куку и заводили: вернувшемуся
 * посетителю. Платить видимым дефектом за то, чтобы список показывал
 * город на странице, содержимое которой от города не зависит, — плохой
 * размен, а держать куку, которую после этого никто не читает, шаблон
 * не имеет права: сущность без потребителя.
 *
 * Правило теперь простое: **переключатель показывает то, что говорит
 * адрес.** Там, где город есть в адресе, он приходит с сервера и верен
 * с первого кадра; где города в адресе нет — список нейтрален, и это
 * честно: страница и правда не про город.
 *
 * Если кросс-визитная память когда-нибудь понадобится, делать её нужно
 * не кукой на клиенте, а частичным пререндером (`experimental.ppr`):
 * он позволяет отдать статикой всю страницу, кроме одной динамической
 * дырки. Это осознанный шаг с экспериментальным флагом, а не правка
 * этого файла.
 */
export function useCityNavigate(citySlugs: readonly string[]) {
  const router = useRouter()
  const pathname = usePathname()
  const { logical, cityAware, city } = parsePath(pathname, citySlugs)

  /**
   * Выбор, сделанный на обычной странице. Живёт, пока жив компонент,
   * и нужен ровно затем, чтобы список не отпрыгивал обратно на «Весь
   * Казахстан» под пальцем: там менять нечего — ни адрес, ни содержимое —
   * но нажатие обязано быть видно.
   */
  const [picked, setPicked] = useState<string | null>(null)

  function changeCity(value: string) {
    const slug = value === ALL_CITIES ? '' : value
    setPicked(slug || null)

    // Обычной странице менять адрес некуда, а содержимое от города
    // не зависит — перерисовывать нечего.
    if (!cityAware) return

    router.push(slug ? cityPath(slug, logical) : logical)
  }

  /**
   * Адрес сильнее всего: есть город в адресе — показываем его. Нет города,
   * но страница городская (`/uslugi`) — это осознанный «Весь Казахстан».
   * И только на обычной странице показывается то, что человек выбрал
   * сам, здесь и сейчас.
   */
  const activeSlug = city ?? (cityAware ? null : picked)

  return { changeCity, activeSlug }
}
