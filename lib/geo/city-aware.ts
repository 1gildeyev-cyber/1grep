/**
 * Единственный список «городских» логических корней: разделов сайта,
 * у которых кроме общей версии есть версия, привязанная к городу
 * (адрес вида `/<город>/<корень>...`).
 *
 * Источник правды для двух модулей, которые иначе описывали бы одно
 * и то же порознь:
 *  - `lib/geo/parse-path.ts` — по этому списку решает, city-aware ли
 *    текущий адрес, то есть можно ли подменить город в URL, не потеряв
 *    страницу (от этого зависит переключатель города);
 *  - `lib/matrix.ts` — по этому списку решает, для каких путей собирать
 *    городские версии при перечислении матрицы (sitemap, чек-лист главной).
 *
 * Разойдись эти два списка — получится ровно тот дефект, ради устранения
 * которого делается мультигео: переключатель уведёт на страницу, которой
 * нет в матрице (404), либо наоборот — sitemap пообещает поисковику
 * страницу, которую переключатель не показывает.
 *
 * Корень `/` (главная) в списке не участвует: у него нет сегмента-имени —
 * оба модуля обрабатывают пустой логический путь как city-aware сами
 * по себе, без обращения к этому списку.
 */
export const CITY_AWARE_ROOTS: readonly string[] = ['uslugi']
